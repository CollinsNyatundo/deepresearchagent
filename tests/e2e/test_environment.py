import hmac
import hashlib
import jwt
from fastapi.testclient import TestClient

from research_engine.api import app
from research_engine.auth import get_supabase_jwt_secret

def test_imports():
    """Verify that backend server modules and JWT/cryptography imports function correctly."""
    assert app is not None
    assert get_supabase_jwt_secret() is not None

def test_jwt_fixture_generation(generate_mock_jwt, jwt_secret):
    """Verify that the mock JWT token generated by the fixture can be successfully validated and decoded."""
    token = generate_mock_jwt(user_id="test-user", email="test@example.com")
    assert isinstance(token, str)
    
    # Decode and verify the payload
    payload = jwt.decode(token, jwt_secret, algorithms=["HS256"], audience="authenticated")
    assert payload["sub"] == "test-user"
    assert payload["email"] == "test@example.com"
    assert payload["role"] == "authenticated"

def test_hmac_signature_generation(generate_webhook_signature, webhook_shared_secret):
    """Verify that the HMAC signature generator fixture computes correct SHA-256 signatures."""
    payload = b"test-webhook-payload-bytes"
    sig = generate_webhook_signature(payload)
    
    # Recalculate manually to verify correctness
    expected = hmac.new(
        webhook_shared_secret.encode("utf-8"),
        payload,
        hashlib.sha256
    ).hexdigest()
    
    assert sig == expected

def test_test_client_headers(e2e_test_client: TestClient):
    """Verify that the e2e test client is pre-configured with the default authorization headers."""
    auth_header = e2e_test_client.headers.get("Authorization")
    assert auth_header is not None
    assert auth_header.startswith("Bearer ")
    
    # Try calling a simple unauthenticated public endpoint (e.g. health check) using the client
    response = e2e_test_client.get("/health")
    assert response.status_code == 200
    assert response.json()["status"] == "ok"
